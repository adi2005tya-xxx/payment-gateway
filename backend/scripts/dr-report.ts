/** Renders docs/dr-test-report.md from docs/dr-test-report.json (measured results) + docs/dr-test-analysis.md (hand-written findings). */
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';

const docs = resolve('..', 'docs');
const r = JSON.parse(readFileSync(resolve(docs, 'dr-test-report.json'), 'utf8'));
const analysisPath = resolve(docs, 'dr-test-analysis.md');
const secs = (ms: number | undefined) => (ms === undefined ? 'n/a' : `${(ms / 1000).toFixed(1)} s`);
const m = r.metrics;
const lines: string[] = [];
const out = (s = '') => lines.push(s);

out('# Disaster recovery test report');
out();
out(`Generated by \`scripts/dr-drill.ts\` on ${r.generatedAt}. **Every number below was measured in that run; nothing is estimated.**`);
out();
out(`**Result: ${r.result}** (${r.steps.filter((s: any) => s.ok).length}/${r.steps.length} steps passed)`);
out();
out('## Environment');
out(`- OS: ${r.environment.os}, ${r.environment.cpus} CPUs, ${r.environment.memGB} GB RAM, Node ${r.environment.node}`);
out(`- Database: PostgreSQL ${r.environment.postgres} (real server, binaries from the \`embedded-postgres\` dev dependency), trust auth on 127.0.0.1, disposable data directories`);
out('- Backup method: physical base backup using the low-level API (`pg_backup_start` / `pg_backup_stop`) plus continuous WAL archiving, restored with `recovery_target_time` (PITR). `pg_dump`/`pg_basebackup` binaries are not part of the embedded package, so logical dumps were not exercised.');
out('- Backups and the WAL archive live in directories on the **same disk** as the test cluster. This test proves the mechanics, **not** separation of failure domains (see gaps).');
out('- Data: synthetic only (3 merchants, payments, refunds, payouts incl. processing/ambiguous/held, pending refund, queued webhook, unresolved reconciliation items).');
out();
out('## Results by scenario');
out();
out('| Scenario | Step | Result | Time |');
out('|---|---|---|---|');
for (const s of r.steps) out(`| ${s.scenario} | ${s.name} | ${s.ok ? 'PASS' : '**FAIL**'} | ${secs(s.ms)} |`);
out();
const failed = r.steps.filter((s: any) => !s.ok);
if (failed.length) {
  out('### Failures (exact output)');
  for (const f of failed) out(`- **${f.scenario} / ${f.name}**: \`${String(f.detail).replace(/`/g, "'").slice(0, 800)}\``);
  out();
}
out('## Measured recovery objectives');
out();
if (m.backup) {
  out('### Backup');
  out(`- Base backup: ${m.backup.files} files, ${(m.backup.encryptedBytes / 1048576).toFixed(1)} MiB encrypted; copy ${secs(m.backup.copyMs)}, encrypt ${secs(m.backup.encryptMs)}`);
  out(`- WAL archive at end of drill: ${m.wal?.count} segments (16 MiB each, encrypted individually)`);
}
if (m.crashRecoveryMs) out(`- Crash (immediate stop) + restart + WAL replay: ${secs(m.crashRecoveryMs)}`);
out();
out('### Recovery time (RTO) as measured');
out();
out('| Restore | Decrypt + verify + extract | Start + WAL replay + promote | Integrity verification | Total to verified |');
out('|---|---|---|---|---|');
for (const [label, x] of [['PITR to target time', m.pitr], ['Latest archived state', m.latest]] as const) {
  if (x) out(`| ${label} | ${secs(x.extractMs)} | ${secs(x.recoveryMs)} | ${secs(x.verifyMs)} (${x.checks} checks) | **${secs(x.extractMs + x.recoveryMs + x.verifyMs)}** |`);
}
out();
out('These figures are for a ~' + (m.backup ? (m.backup.encryptedBytes / 1048576).toFixed(0) : '?') + ' MiB synthetic database on one developer machine and do **not** extrapolate linearly to production volumes. They exclude detection time, decision time, provisioning, DNS/traffic cut-over, and the manual post-restore reconciliation/release steps.');
out();
out('### Recovery point (RPO) as measured');
out();
if (m.rpo) {
  out(`- With WAL archiving (\`archive_timeout = 60 s\`), a batch of ${m.batch3Payments ?? '?'} payments and 1 payout committed immediately before total loss of the primary was **${m.rpo.unarchivedBatchLost ? 'LOST' : 'recovered'}** (it was still in the un-archived current WAL segment). Everything up to the last archived segment was recovered exactly.`);
  out('- Achievable RPO therefore equals the interval between archived WAL segments (bounded by `archive_timeout`, plus archive latency) when only archiving is used. **Synchronous replication to a second site would be needed for RPO near zero**; it is not configured here.');
  out('- Without WAL archiving, RPO = time since the last base backup.');
}
if (m.staleRestore) {
  out();
  out('### Stale restore (point-in-time earlier than reality)');
  out(`- Auto-detected restore on application start: **${m.staleRestore.autoDetected}** (database incarnation/timeline changed)`);
  const rep = m.staleRestore.report;
  out(`- Post-restore procedure: sessions revoked ${rep.sessionsRevoked}, payments recovered from provider ${rep.paymentsRecovered}, payouts synced from provider ${rep.payoutsSynced}, payouts held ${rep.payoutsHeldForReview}, queued payouts left unsubmitted ${rep.payoutsQueuedNotSubmitted}, pending refunds ${rep.refundsPendingNotSubmitted}`);
  out(`- Open reconciliation kinds after restore: ${m.staleRestore.openReconciliationKinds.join(', ') || 'none'}; release of the money-out freeze blocked by: **${m.staleRestore.unfreezeBlockedBy}**`);
  out('- External payouts created by the restore and by workers while frozen: **0**');
}
if (m.suiteOnRestored) {
  out();
  out('### Existing test suite against the restored server');
  out(`- ${m.suiteOnRestored.suites}; ${m.suiteOnRestored.tests}; exit code ${m.suiteOnRestored.exitCode}; ${secs(m.suiteOnRestored.ms)}`);
}
out();
if (existsSync(analysisPath)) {
  out(readFileSync(analysisPath, 'utf8'));
}
writeFileSync(resolve(docs, 'dr-test-report.md'), lines.join('\n') + '\n');
console.log('wrote docs/dr-test-report.md');
